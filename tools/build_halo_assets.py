"""Generate src/HaloAssets.h: the logo outline tour for the laser startup.

Source: assets/source/logo_contours.json (pixel contours of the approved logo mask, 640 x 259).
Placement is the same as the approved logo on the dial: width 280 px, centred at 233,233.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/source/logo_contours.json'
TARGET = ROOT / 'OJM_DDE_Dynamics/src/HaloAssets.h'
WIDTH, HEIGHT = 640, 259
SCALE = 280 / WIDTH
LEFT, TOP = 233 - 140, 233 - HEIGHT * SCALE / 2


def run():
    contours = json.loads(SOURCE.read_text(encoding='utf-8'))
    lines = ['#pragma once',
             '// GENERATED by tools/build_halo_assets.py from assets/source/logo_contours.json. Do not edit.',
             '// Logo outline tour for the laser phase of the startup (screen pixels, same placement as the logo).',
             'struct HaloPoint {float x,y;};',
             'struct HaloContour {const HaloPoint *points; uint16_t count;};']
    total = 0
    for index, contour in enumerate(contours):
        points = [(LEFT + x * SCALE, TOP + y * SCALE) for x, y in contour['points']]
        total += len(points)
        body = ','.join(f'{{{x:.3f}f,{y:.3f}f}}' for x, y in points)
        lines.append(f'static const HaloPoint HALO_CONTOUR_{index}[] = {{{body}}};')
    lines.append('static const HaloContour HALO_CONTOURS[] = {' + ','.join(
        f'{{HALO_CONTOUR_{i},{len(c["points"])}}}' for i, c in enumerate(contours)) + '};')
    lines.append(f'static constexpr uint8_t HALO_CONTOUR_COUNT = {len(contours)};')
    lines.append(f'static constexpr uint16_t HALO_CONTOUR_POINTS = {total};')
    TARGET.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{TARGET.name}: {len(contours)} contours, {total} points')


if __name__ == '__main__':
    run()
